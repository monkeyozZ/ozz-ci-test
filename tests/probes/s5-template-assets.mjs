import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { setTimeout as delay } from 'node:timers/promises';
const { RegistryAdapter } = await import(
  process.env.S5_ASSET_REGISTRY_MODULE ||
    new URL('../../packages/infrastructure/dist/registry.js', import.meta.url).href
);

// Maintainer-only asset verification. Product startup never resolves moving tags.
const root = new URL('../../', import.meta.url);
const candidates = {
  postgresql: 'postgres:17.11-bookworm',
  redis: 'redis:7.4.11-bookworm',
  'node-example': 'node:24.22.1-alpine3.24',
  'static-example': 'nginx:1.28.3-alpine3.23',
};
const resolver = new RegistryAdapter({
  httpProxy: process.env.REGISTRY_HTTP_PROXY || undefined,
  proxyBlobOrigins: (process.env.REGISTRY_PROXY_BLOB_ORIGINS || '').split(',').filter(Boolean),
});
const results = await Promise.allSettled(
  Object.entries(candidates).map(async ([id, reference]) => {
    for (let attempt = 1; attempt <= 2; attempt++) {
      try {
        return [
          id,
          await resolver.resolve(reference, {
            platforms: [
              { os: 'linux', architecture: 'arm64' },
              { os: 'linux', architecture: 'amd64' },
            ],
          }),
        ];
      } catch (error) {
        if (attempt === 2 || !error.retryable)
          throw Object.assign(new Error('Asset verification failed'), { id, code: error.code });
        await delay(1000);
      }
    }
  }),
);
const failures = results.filter((result) => result.status === 'rejected');
if (failures.length) {
  const report = {
    status: 'failed',
    observedAt: new Date().toISOString(),
    failures: failures.map((r) => ({ id: r.reason.id, code: r.reason.code })),
    verified: results.filter((r) => r.status === 'fulfilled').map((r) => r.value),
  };
  await mkdir(new URL('.local/s5-asset-attempts/', root), { recursive: true });
  await writeFile(
    new URL(`.local/s5-asset-attempts/${Date.now()}.json`, root),
    JSON.stringify(report, null, 2) + '\n',
  );
  console.error(
    JSON.stringify({
      status: report.status,
      failures: report.failures,
      verified: report.verified.map(([id]) => id),
    }),
  );
  process.exitCode = 1;
} else {
  const images = Object.fromEntries(results.map((r) => r.value));
  const directory = new URL('packages/control-plane/src/templates/', root);
  await mkdir(directory, { recursive: true });
  await writeFile(
    new URL('image-assets.ts', directory),
    "import type { ResolvedImage } from '@ozz/infrastructure/registry';\n\n" +
      '// Generated by tests/probes/s5-template-assets.mjs; immutable index and platform identities.\n' +
      `export const templateImages = ${JSON.stringify(images, null, 2)} satisfies Record<string, ResolvedImage>;\n`,
    { flag: 'w' },
  );
  const report = {
    stage: 'S5',
    status: 'passed',
    verifiedAt: new Date().toISOString(),
    checks: Object.entries(images).map(([id, image]) => ({
      id,
      input: image.inputReference,
      digest: image.manifestDigest,
      platforms: image.platformManifests,
      status: 'passed',
    })),
    limitation:
      'Registry manifest/config verification only; runtime/database/data validation is separate.',
  };
  await writeFile(
    new URL('docs/acceptance/s5-template-assets-results.json', root),
    JSON.stringify(report, null, 2) + '\n',
  );
  console.log(
    JSON.stringify({
      status: 'passed',
      count: report.checks.length,
      artifact: fileURLToPath(new URL('image-assets.ts', directory)),
    }),
  );
}
